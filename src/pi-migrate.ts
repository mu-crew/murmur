// `murmur pi migrate`: retire the pre-package `murmur link pi` install.
//
// pi now loads murmur as a package (`pi install npm:@mu-crew/murmur`). A
// leftover ~/.pi/agent/extensions/murmur.ts shim would load a SECOND copy of
// the extension in the same process; both claim the pane with the same pid, the
// store answers `retained` to each, and every event is reported twice. So the
// shim must leave pi's discovery path.
//
// Only a file murmur itself generated is moved, and moved aside, never deleted.
// Ownership is proven, not inferred from a name: a regular file equal to one of
// the shim templates released `link pi` versions wrote, where only the two
// generated paths may differ, and only in their generated form (absolute paths
// to this package's dist/extension/ files). A `link pi --copy` install, an
// edited shim or a symlink is reported and left alone.

import { lstatSync, readFileSync, renameSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, isAbsolute, join } from "node:path";
import { ensureDir } from "./dirs.js";

export type MigrateState = "absent" | "shim" | "foreign";

export interface MigrateResult {
  path: string;
  state: MigrateState;
  moved: boolean;
  /** Where it went (apply only). */
  to?: string;
  guidance: string[];
}

const HEAD = `// murmur:shim
// Generated by \`murmur link pi\`. Do not edit.
//
// A re-export, not a copy: the extension code lives in the murmur install, so
// upgrading murmur upgrades the extension with no reinstall step. Re-run
// \`murmur link pi\` only if the install path itself moves.
//
`;

/** The comment block between HEAD and the store line, per released template:
 *  v0.2.0-v0.2.2 and v0.2.3-v1.4.0 (test/fixtures/link-shim-*.txt, rendered
 *  from those tags). Only the comments changed. v0.1.x wrote an inlined copy. */
const BODIES = [
  `// The store path is set here rather than resolved by the extension. A bare
// specifier cannot resolve from ~/.pi/agent/extensions, and the failure is
// silent: the import throws, the extension swallows it, and every state report
// is dropped while the tmux badge still paints.
//
// A dynamic import, not \`export ... from\`: ESM hoists static re-exports above
// this assignment, so the extension loaded before the variable was set and read
// undefined. Verified -- the static form printed \`undefined\` in the target.
`,
  `// The store path is set here rather than resolved by the extension: a bare
// specifier cannot resolve from ~/.pi/agent/extensions, and the failure is
// silent -- the import throws, the extension swallows it, and every report is
// dropped while the tmux badge still paints.
//
// A dynamic import, not \`export ... from\`: ESM hoists static re-exports above
// this assignment, so the extension read undefined. Verified -- the static form
// printed \`undefined\` in the target.
`,
];

const TAIL =
  /^process\.env\.MURMUR_STORE_MODULE \?\?= ("[^\n]*");\n\nconst \{ default: extension \} = await import\(("[^\n]*")\);\nexport default extension;\n$/;

/** A JSON-quoted absolute path ending in `/dist/extension/<file>`, as `link pi` wrote it. */
function isGeneratedPath(literal: string, file: string): boolean {
  try {
    const path: unknown = JSON.parse(literal);
    return (
      typeof path === "string" &&
      JSON.stringify(path) === literal &&
      isAbsolute(path) &&
      path.replaceAll("\\", "/").endsWith(`/dist/extension/${file}`)
    );
  } catch {
    return false;
  }
}

export function isMurmurShimText(text: string): boolean {
  if (!text.startsWith(HEAD)) return false;
  const rest = text.slice(HEAD.length);
  const body = BODIES.find((b) => rest.startsWith(b));
  if (body === undefined) return false;
  const match = TAIL.exec(rest.slice(body.length));
  return (
    match !== null &&
    isGeneratedPath(match[1] ?? "", "store.js") &&
    isGeneratedPath(match[2] ?? "", "murmur-pi.js")
  );
}

function lstatOrUndefined(path: string): ReturnType<typeof lstatSync> | undefined {
  try {
    return lstatSync(path);
  } catch {
    return undefined;
  }
}

/** A name next to `dest` that does not exist yet, so a parked file is never overwritten. */
function freeName(dest: string): string {
  if (!lstatOrUndefined(dest)) return dest;
  for (let i = 1; ; i++) {
    const candidate = `${dest}.${i}`;
    if (!lstatOrUndefined(candidate)) return candidate;
  }
}

export function migratePi(opts: { home?: string; apply?: boolean } = {}): MigrateResult {
  const home = opts.home ?? process.env.MURMUR_PI_HOME ?? homedir();
  const path = join(home, ".pi", "agent", "extensions", "murmur.ts");
  const st = lstatOrUndefined(path);
  let state: MigrateState = "absent";
  if (st) {
    let text = "";
    try {
      if (st.isFile()) text = readFileSync(path, "utf8");
    } catch {
      // Unreadable: not provably ours.
    }
    state = isMurmurShimText(text) ? "shim" : "foreign";
  }
  const result: MigrateResult = { path, state, moved: false, guidance: [] };

  if (opts.apply === true && state === "shim") {
    // `.shim`, not `.ts`: pi loads every *.ts under extensions/ and ignores the rest.
    const to = freeName(join(home, ".pi", "agent", "disabled", "murmur.ts.shim"));
    ensureDir(dirname(to));
    renameSync(path, to);
    result.to = to;
    result.moved = true;
  }

  if (opts.apply !== true && state === "shim") {
    result.guidance.push("Nothing moved. Re-run with --apply to move the murmur shim aside.");
  }
  if (state === "foreign") {
    result.guidance.push(
      `Left ${path} in place: not proven murmur's (a \`link pi --copy\` install, a v0.1 \`link pi\` copy, or an edited file). If it duplicates the package, move it aside yourself.`,
    );
  }
  if (result.moved) {
    result.guidance.push(
      "Running pi agents keep the old extension until they restart: restart pi or run /reload.",
    );
  }
  result.guidance.push("Install the package once: pi install npm:@mu-crew/murmur");
  return result;
}
